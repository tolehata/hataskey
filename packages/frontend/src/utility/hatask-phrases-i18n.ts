const translationLookup = HATASK_PHRASE_TRANSLATIONS as Readonly<Record<string, HataskPhraseTranslation>>;
const TODAY_EVENT_PREFIX = '今日の予定: ';

function translateLine(source: string, target: 'en' | 'zh'): string {
	const translated = translationLookup[source];
	if (translated) return translated[target];
	if (source.startsWith(TODAY_EVENT_PREFIX)) {
		const title = source.slice(TODAY_EVENT_PREFIX.length);
		return target === 'en' ? `Today's schedule: ${title}` : `今天的安排：${title}`;
	}
	return source;
}

/**
 * HataEye が生成した固定文だけを翻訳する。
 * 辞書にない文（利用者が入力した予定名など）は原文のまま返す。
 */
export function translateHataskPhrase(source: string, lang: string): string {
	const normalized = lang.toLowerCase();
	const target = normalized.startsWith('en') ? 'en' : normalized.startsWith('zh') ? 'zh' : null;
	if (target == null) return source;
	return source.split('\n').map(line => translateLine(line, target)).join('\n');
}
